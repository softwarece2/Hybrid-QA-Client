// Function to parse tab-separated data
const parseData = (dataString) => {
    const lines = dataString.split("\n");
    const headers = lines[0].split("\t");
    const rows = lines.slice(1).map((line) => line.split("\t").map(parseFloat));

    const columns = {};
    headers.forEach((header, i) => {
        columns[header] = rows.map((row) => row[i]);
    });

    return columns;
};

const PhotoGrammetry = () => {
    const data = parseData(df);
    const { X1, Y1, Z1, Mag } = data;
    const scalingFactor = 15;

    const scatterPoints = {
        x: X1,
        y: Y1,
        z: Z1,
        mode: "markers",
        marker: { size: 3, color: "black" },
        type: "scatter3d",
        name: "noncoded.txt",
    };

    const surface = {
        x: X1,
        y: Y1,
        z: Z1,
        color: "aqua",
        opacity: 0.3,
        type: "mesh3d",
        name: "Surface",
        hoverinfo: "x+y+z", 
    };
    const displacementVectors = {
        type: "cone",
        x: X1,
        y: Y1,
        z: Z1,
        u: new Array(X1.length).fill(0),
        v: Mag.map((m) => m * scalingFactor),
        w: new Array(X1.length).fill(0),
        colorscale: [[0, "green"], [1, "green"]],
        sizemode: "absolute",
        cmin: -2.10,   // Set legend scale minimum
        cmax: 2.10, 
        sizeref: 3.0,
        opacity: 1.0,
        name: "Displacement",
        showscale: true,
        hovertemplate: "Magnitude: %{customdata}", 
        customdata: Mag, 
    };
    // Add scatter points with text labels at cone positions
    const displacementLabels = {
        type: "scatter3d",
        x: X1,
        y: Y1,
        z: Z1,
        mode: "text",
        text: Mag.map((m) => `${m.toFixed(2)}`), 
        textposition: "top center",
        textfont: { size: 15, color: "black" }, 
        name: "Displacement Values", 
        showlegend: false, 
    };
    const layout = {
        title: "3D Vector Visualization",
        autosize: true,
        margin: { l: 0, r: 0, t: 40, b: 0 }, // Remove extra margins
        scene: {
            xaxis: { title: "X Axis" },
            yaxis: { title: "Y Axis" },
            zaxis: { title: "Z Axis" },
        },
        legend: {
            orientation: "h",  // Moves legend title above the legend
            x: 1.07,              // Aligns to the right
            y: 0,            // Moves it above the legend
            xanchor: "right",  // Ensures correct alignment
        },
    };
    

    return (
        <div style={{ width: "80vw", height: "80vh", display: "flex", justifyContent: "center", alignItems: "center" }}>
        <Plot 
            data={[scatterPoints, surface, displacementVectors, displacementLabels]} 
            layout={layout} 
            useResizeHandler={true} 
            style={{ width: "100%", height: "100%" }} 
        />
    </div>
    );
};

